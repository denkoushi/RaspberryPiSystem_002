import { describe, expect, it } from 'vitest';

import { normalizeSpokenSeiban } from './normalizeSpokenSeiban';

describe('normalizeSpokenSeiban', () => {
  it.each([
    ['にーろくの いちぜろよんいち', '26-1041'],
    ['26の1041', '26-1041'],
    ['二六ハイフン一〇四一', '26-1041'],
    ['２６－１０４１。', '26-1041'],
    ['cand ハイフン 200', 'CAND-200'],
    ['二十六の千四十一', '26-1041'],
    ['にじゅうろくのせんよんじゅういち', '26-1041'],
    ['ニジュウロクノイチゼロヨンイチ', '26-1041'],
    ['零〇一二三四五六七八九', '00123456789'],
    ['ぜろれいまるいちににーさんよんしごごーろくななしちはちきゅうく', '00012234455677899'],
    ['ゼロレイマルイチニニーサンヨンシゴゴーロクナナシチハチキュウク', '00012234455677899'],
    ['26ー1041', '26-1041'], ['1ー2ー3', '1-2-3'],
    ['26−1041', '26-1041'], ['26‐1041', '26-1041'],
    ['二六マイナス一零四一', '26-1041'],
    ['Ａｂｃ ノ ０１２、３.４,５。', 'ABC-012345'],
    ['十', '10'], ['百', '100'], ['千', '1000'],
    ['九千九百九十九', '9999'], ['ひゃくにじゅうさん', '123'],
    ['一百一', '101'], ['にーじゅうごー', '25'],
    ['000', '000'], [' CAND-200\n', 'CAND-200'], ['-1--', '-1--']
  ])('%s → %s', (spoken, expected) => {
    expect(normalizeSpokenSeiban(spoken)).toBe(expected);
  });
  it.each([
    '', '  、。. , ', 'ご視聴ありがとうございました', 'ABC', '---',
    'A/200', '26_1041', '26+1041', '26🙂', 'CANDー200', 'ー26', '26ー',
    '二十十', '百千', '二六十', '零十', '十零', '一万', 'まん',
    'さんびゃく', 'ろっぴゃく', 'はっせん', 'えーびー200', 'twenty six', '「26」'
  ])('rejects %s', spoken => {
    expect(normalizeSpokenSeiban(spoken)).toBeNull();
  });
});
